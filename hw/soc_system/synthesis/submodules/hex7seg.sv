module hex7seg(input logic  [3:0] a,
	       output logic [6:0] y);

   always_comb begin
       case (a)
            4'b0000: y = 7'b1000000;    //0
            4'b0001: y = 7'b1111001;    //1
            4'b0010: y = 7'b0100100;    //2
            4'b0011: y = 7'b0110000;    //3
            4'b0100: y = 7'b0011001;    //4
            4'b0101: y = 7'b0010010;    //5
            4'b0110: y = 7'b0000010;    //6
            4'b0111: y = 7'b1111000;    //7
            4'b1000: y = 7'b0000000;    //8
            4'b1001: y = 7'b0010000;    //9
            4'b1010: y = 7'b0001000;    //10 A
            4'b1011: y = 7'b0000011;    //11 b
            4'b1100: y = 7'b1000110;    //12 C
            4'b1101: y = 7'b0100001;    //13 d
            4'b1110: y = 7'b0000110;    //14 E
            4'b1111: y = 7'b0001110;    //15 F
            default: y = 7'b1111111;    //unknown
       endcase
   end
   
endmodule
